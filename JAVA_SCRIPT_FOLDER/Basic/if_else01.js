const mark=40;

if (mark >= 90){
    console.log("A+");
    
}
else if (mark >= 80){
    console.log("A");
}
else if (mark >= 70){
    console.log("B+");
    
}
else if (mark >= 60){
    console.log("B");
    
}
else if (mark >= 50){
    console.log("C");
    
}
else if (mark  < 50  &&  mark >= 30){
    console.log("D");
    
}
else{
    console.log("Fail");
    
}